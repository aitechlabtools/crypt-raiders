// Prueba del Vestuario y la Tienda (maqueta): desbloquear, ponerse un aspecto y ver que la tienda no vende nada.
const { chromium, devices } = require('playwright');
const BASE = process.argv[2] || 'http://localhost:5173/play/';
const OUT = process.argv[3] || '/tmp/claude-0/wardrobe';
const DEVICE = process.argv[4];
(async () => {
  require('fs').mkdirSync(OUT, { recursive: true });
  const b = await chromium.launch();
  const ctx = DEVICE ? await b.newContext({ ...devices[DEVICE] }) : await b.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await ctx.newPage();
  const errors = [];
  page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
  page.on('pageerror', (e) => errors.push(e.message));
  const tap = async (sel) => { await page.waitForSelector(sel, { timeout: 8000 }); await page.click(sel); };
  await page.goto(BASE + '?debug');
  await page.evaluate(() => indexedDB.deleteDatabase('cryptraiders'));
  await page.reload();
  await tap('[data-testid=btn-play]');
  await page.fill('[data-testid=name-input]', 'Vestida');
  await tap('[data-testid=class-warrior]');
  await tap('[data-testid=btn-create]');
  await tap('[data-testid=btn-tutorial-ok]');
  await page.evaluate(() => { const d = window.__CRYPTRAIDERS__; const p = d.getState().profile; d.setState({ profile: { ...p, cosmetics: ['cos_ossuary_helm', 'cos_redclaw_mail', 'cos_umbral_blade', 'cos_umbral_staff'], equipment: { ...p.equipment, helmet: { uid: 'h', itemId: 'iron_helm', qty: 1 } } } }); });
  await tap('[data-testid=tab-wardrobe]');
  await page.screenshot({ path: `${OUT}/wardrobe.png` });
  await tap('[data-testid=wear-cos_ossuary_helm]');
  await tap('[data-testid=wear-cos_redclaw_mail]');
  await tap('[data-testid=wear-cos_umbral_blade]');
  await page.waitForTimeout(300);
  const st = await page.evaluate(() => { const p = window.__CRYPTRAIDERS__.getState().profile; return { wardrobe: p.wardrobe, helmet: p.equipment.helmet.itemId }; });
  console.log('vestuario:', JSON.stringify(st.wardrobe), '· casco real:', st.helmet);
  await page.screenshot({ path: `${OUT}/wardrobe-dressed.png` });
  await tap('[data-testid=tab-shop]');
  console.log('tienda:', await page.$eval('[data-testid=shop-closed]', (e) => e.textContent));
  const buys = await page.$$eval('[data-testid^=shop-buy-]', (bs) => bs.map((x) => x.disabled));
  console.log('botones de compra desactivados:', buys.length, buys.every(Boolean));
  await page.screenshot({ path: `${OUT}/shop.png` });
  await tap('[data-testid=tab-play]');
  await tap('[data-testid=btn-enter-dungeon]');
  await tap('[data-testid=btn-dungeon-tutorial-ok]');
  await page.waitForTimeout(800);
  await page.screenshot({ path: `${OUT}/dungeon-dressed.png` });
  console.log('errores:', errors.length ? errors : 'ninguno');
  await b.close();
})().catch((e) => { console.error('FALLO', e); process.exit(1); });
